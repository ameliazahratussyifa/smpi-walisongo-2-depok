-- 1. Tabel PPDB Pendaftar
CREATE TABLE IF NOT EXISTS ppdb_pendaftar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomor_registrasi TEXT UNIQUE NOT NULL,
    nama_lengkap TEXT NOT NULL,
    nisn TEXT NOT NULL,
    nik TEXT,
    jenis_kelamin TEXT NOT NULL,
    tempat_lahir TEXT,
    tanggal_lahir TEXT,
    asal_sekolah TEXT NOT NULL,
    nama_wali TEXT NOT NULL,
    no_wa_wali TEXT NOT NULL,
    alamat_lengkap TEXT,
    jalur_pendaftaran TEXT NOT NULL,
    pilihan_peminatan TEXT DEFAULT 'Reguler & Tahfidz',
    status_seleksi TEXT DEFAULT 'Menunggu Verifikasi Berkas',
    catatan TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Tabel Berita & Informasi
CREATE TABLE IF NOT EXISTS berita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    kategori TEXT NOT NULL,
    ringkasan TEXT NOT NULL,
    konten TEXT NOT NULL,
    penulis TEXT NOT NULL,
    tanggal TEXT NOT NULL,
    gambar TEXT,
    is_featured INT DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Tabel Dewan Guru & Staf
CREATE TABLE IF NOT EXISTS guru (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    jabatan TEXT NOT NULL,
    bidang_studi TEXT NOT NULL,
    pendidikan TEXT NOT NULL,
    foto TEXT,
    urutan INT DEFAULT 0
);

-- 4. Tabel Ekstrakurikuler
CREATE TABLE IF NOT EXISTS ekskul (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    kategori TEXT NOT NULL,
    deskripsi TEXT NOT NULL,
    pembina TEXT NOT NULL,
    jadwal TEXT NOT NULL,
    prestasi TEXT,
    icon TEXT,
    badge TEXT
);

-- 5. Tabel Testimoni
CREATE TABLE IF NOT EXISTS testimoni (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    status TEXT NOT NULL,
    angkatan_relasi TEXT,
    pesan TEXT NOT NULL,
    rating INT DEFAULT 5,
    avatar_initials TEXT
);

-- 6. Tabel Pesan Masuk & Konseling
CREATE TABLE IF NOT EXISTS pesan_kontak (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    email TEXT,
    no_whatsapp TEXT NOT NULL,
    kategori TEXT NOT NULL,
    subjek TEXT NOT NULL,
    pesan TEXT NOT NULL,
    status TEXT DEFAULT 'Belum Dibaca',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. Tabel Cek Raport & Kelulusan Demo
CREATE TABLE IF NOT EXISTS siswa_raport (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nisn TEXT UNIQUE NOT NULL,
    nama_siswa TEXT NOT NULL,
    kelas TEXT NOT NULL,
    semester TEXT NOT NULL,
    tahun_ajaran TEXT NOT NULL,
    status_kelulusan TEXT NOT NULL,
    nilai_pabp INT,
    nilai_ppkn INT,
    nilai_bindo INT,
    nilai_binggris INT,
    nilai_matematika INT,
    nilai_ipa INT,
    nilai_ips INT,
    nilai_tahfidz TEXT,
    akhlak TEXT
);

-- Enable Row Level Security (RLS) & Public Access Policies
ALTER TABLE ppdb_pendaftar ENABLE ROW LEVEL SECURITY;
ALTER TABLE berita ENABLE ROW LEVEL SECURITY;
ALTER TABLE guru ENABLE ROW LEVEL SECURITY;
ALTER TABLE ekskul ENABLE ROW LEVEL SECURITY;
ALTER TABLE testimoni ENABLE ROW LEVEL SECURITY;
ALTER TABLE pesan_kontak ENABLE ROW LEVEL SECURITY;
ALTER TABLE siswa_raport ENABLE ROW LEVEL SECURITY;

-- Allow Public Read Access
CREATE POLICY "Public Read Berita" ON berita FOR SELECT USING (true);
CREATE POLICY "Public Read Guru" ON guru FOR SELECT USING (true);
CREATE POLICY "Public Read Ekskul" ON ekskul FOR SELECT USING (true);
CREATE POLICY "Public Read Testimoni" ON testimoni FOR SELECT USING (true);
CREATE POLICY "Public Read Raport" ON siswa_raport FOR SELECT USING (true);
CREATE POLICY "Public Read PPDB" ON ppdb_pendaftar FOR SELECT USING (true);

-- Allow Public Insert for PPDB and Contact messages
CREATE POLICY "Public Insert PPDB" ON ppdb_pendaftar FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Insert Pesan" ON pesan_kontak FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update PPDB" ON ppdb_pendaftar FOR UPDATE USING (true);

